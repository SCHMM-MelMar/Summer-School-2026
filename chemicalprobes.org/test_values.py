class TestParseDose:
    def test_one_dose(self):
        entries = preprocess.parse_dose("1 mg/Kg")
        assert len(entries) == 1
        value, unit, route = dose_triple(entries[0])
        assert value == 1.0
        assert unit == "mg/kg"
        assert not route

    def test_two_doses_by_two_routes(self):
        entries = preprocess.parse_dose("1 mg/Kg IV, 5 mg/Kg PO")
        assert len(entries) == 2
        first, second = (dose_triple(e) for e in entries)
        assert first == (1.0, "mg/kg", "IV")
        assert second == (5.0, "mg/kg", "PO")

    @pytest.mark.parametrize("raw", ["unknown", "", None])
    def test_no_dose(self, raw):
        assert preprocess.parse_dose(raw) == []

    @pytest.mark.parametrize("raw", ["1 mg/Kg", "1 mg/kg", "1 mgKg", "1 mpk"])
    def test_every_spelling_parses(self, raw):
        entries = preprocess.parse_dose(raw)
        assert len(entries) == 1
        value, unit, _ = dose_triple(entries[0])
        assert value == 1.0
        assert unit

    def test_the_unit_has_one_spelling(self):
        units = {dose_triple(preprocess.parse_dose(raw)[0])[1]
                 for raw in ("1 mg/Kg", "1 mg/kg", "1 mgKg", "1 mpk")}
        assert units == {"mg/kg"}


