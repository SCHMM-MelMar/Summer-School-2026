"""The value-normalising layer of preprocess.py.

TDD: preprocess.py is a skeleton, so every test here is expected to fail with
NotImplementedError until the layer is written. Nothing is generated by running
an implementation -- every number, unit and operator below is written out
literally from the contracts in preprocess.py and the verified ground truths in
REVIEW_FINDINGS.md, so a wrong parser cannot satisfy them by agreeing with
itself.
"""

