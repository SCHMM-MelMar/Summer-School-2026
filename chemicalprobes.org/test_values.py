class TestReviewRegressions:
    @pytest.mark.parametrize("raw, potency, expected", REGRESSIONS)
    def test_regression(self, raw, potency, expected):
        check_rows(raw, potency, expected)

    # a factor of 10^n is never applied silently, so the row is held back
    def test_a_scientific_notation_factor_is_quarantined(self):
        for row in parsed("7.69 x 10^4 per M per sec"):
            assert row["quarantine"]

    # text with no number used to produce a fabricated row
    @pytest.mark.parametrize("raw", [
        "submicromolar", "low uM", "NA", "Helicase activity", "", None,
    ])
    def test_no_number_means_no_row(self, raw):
        assert parsed(raw) == []

    # the '%' of the Dmax beside it: 9.8 is a pIC50 and 9.8 % is meaningless
    def test_a_multi_endpoint_record_does_not_propagate_a_unit(self):
        first, _ = parsed("9.8; 99 % ", "pIC50, Dmax")
        assert first["unit"] != "%"

    # every row carried the comma-joined label of all three endpoints
    def test_the_joined_endpoint_label_never_reaches_a_row(self):
        rows = parsed("63 nM (DC50); 90.8% (Dmax); 52 nM (EC50)", "DC50, Dmax, EC50")
        for row in rows:
            assert row["bioactivity_type"] != "DC50, Dmax, EC50"

    # 0.0 instead of 0.69, which reads as a stronger probe than it is
    def test_a_split_decimal_is_not_zero(self):
        row, = parsed("0. 69 nM", "IC50")
        assert row["value"] != 0.0

    # a censored bound loading as an exact value is the worst failure mode here
    @pytest.mark.parametrize("raw", ["up to 10 µM", "below 1 µM", "< 1 nM"])
    def test_a_censored_value_is_never_exact(self, raw):
        row, = parsed(raw, "IC50")
        assert row["relation"] == "<"

    # a cell line called (K) was a temperature and a species label (H) an hour
    @pytest.mark.parametrize("raw, unit", [
        ("22-166 nM (T), 157 nM (A), 115 nM (B),  85 nM (M)", "nM"),
        ("7.8 nM (human) 2.4 nM  (Mouse)", "nM"),
    ])
    def test_a_parenthesised_label_is_not_a_unit(self, raw, unit):
        for row in parsed(raw, None):
            assert row["unit"] == unit

    # a parenthesised time window still reads as a measurement, so the row it
    # yields has to be caught by the duration rule rather than loaded
    def test_a_time_window_is_never_a_potency(self):
        rows = parsed("15 nM; (32 - 46 nM, 0 - 8 h)", None)
        assert rows[0]["value"] == 15.0
        assert rows[0]["unit"] == "nM"
        assert rows[0]["quarantine"] is None
        for row in rows:
            if row["unit"] in ("h", "min"):
                assert row["quarantine"]
                assert "duration" in row["quarantine"].lower()
