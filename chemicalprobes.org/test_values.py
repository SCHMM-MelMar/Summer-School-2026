# -------------------------------------------------------------- portal_source


def portal_url_sample(n=24):
    """A deterministic sample of the real probe URLs, unsuitables included."""
    path = pathlib.Path(__file__).with_name("ChemicalProbesPortal-6_8_2026.json")
    if not path.exists():
        return []
    urls = sorted({p["URL"] for p in json.loads(path.read_text())["probes"] if p.get("URL")})
    if not urls:
        return []
    two_segments = [u for u in urls if u.count("/") > 3][:4]
    step = max(1, len(urls) // n)
    return sorted(set(urls[::step][:n]) | set(two_segments))


PORTAL_SAMPLE = portal_url_sample() or [
    pytest.param("", marks=pytest.mark.skip(reason="portal export not on disk"))
]


class TestPortalSource:
    def test_one_path_segment(self):
        assert (preprocess.portal_source("https://www.chemicalprobes.org/sgc0946")
                == (PORTAL_PREFIX, "sgc0946"))

    def test_two_path_segments(self):
        # the 260 unsuitable probes live under /unsuitables/ and dropping that
        # builds a 404
        assert (preprocess.portal_source(
            "https://www.chemicalprobes.org/unsuitables/jib-04")
            == (PORTAL_PREFIX, "unsuitables/jib-04"))

    def test_the_prefix_is_the_module_constant(self):
        assert preprocess.PORTAL_PREFIX == PORTAL_PREFIX
        assert (preprocess.portal_source("https://www.chemicalprobes.org/sgc0946")[0]
                == preprocess.PORTAL_PREFIX)

    @pytest.mark.parametrize("url", PORTAL_SAMPLE)
    def test_prefix_plus_path_rebuilds_the_url(self, url):
        xref_id, path = preprocess.portal_source(url)
        assert xref_id + path == url


