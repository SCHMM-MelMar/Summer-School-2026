_PATH = pathlib.Path(__file__).with_name("preprocess.py")
_SPEC = importlib.util.spec_from_file_location("preprocess", _PATH)
preprocess = importlib.util.module_from_spec(_SPEC)
_SPEC.loader.exec_module(preprocess)

# the keys of one parsed potency row, in the order the contract names them
ROW_KEYS = {
    "relation", "value", "value_high", "error", "unit", "unit_inherited",
    "concentration", "concentration_unit", "bioactivity_type", "fragment",
    "raw", "quarantine",
}

DOI_PREFIX = "https://doi.org/"
PUBMED_PREFIX = "https://pubmed.ncbi.nlm.nih.gov/"
PORTAL_PREFIX = "https://www.chemicalprobes.org/"

# a pandas NaN, not a python one: this is the value as_text() actually meets
PANDAS_NAN = pd.Series([1.0, None]).iloc[1]


def parsed(raw, potency=None):
    return preprocess.parse_potency_value(raw, potency)


def check_rows(raw, potency, expected):
    """Compare a parse against a list of {key: value}, one per expected row.

    Only the keys named in each dict are checked. The key 'quarantine_mentions'
    asserts the row is quarantined and that its reason contains a substring the
    docstring of quarantine_reason justifies, so rewording a reason is free.
    """
    rows = parsed(raw, potency)
    assert len(rows) == len(expected), (
        f"{raw!r} -> {len(rows)} rows, expected {len(expected)}: "
        f"{[r.get('value') for r in rows]}"
    )
    for i, (row, want) in enumerate(zip(rows, expected)):
        for key, value in want.items():
            if key == "quarantine_mentions":
                assert row["quarantine"], f"row {i} of {raw!r} is not quarantined"
                assert value in row["quarantine"].lower(), (
                    f"row {i} of {raw!r}: reason {row['quarantine']!r} "
                    f"does not mention {value!r}"
                )
            else:
                assert row[key] == value, (
                    f"row {i} of {raw!r}: {key} is {row[key]!r}, expected {value!r}"
                )


def a_row(**over):
    """One parsed row, clean, for calling quarantine_reason() directly."""
    row = {
        "relation": None, "value": 1.0, "value_high": None, "error": None,
        "unit": "nM", "unit_inherited": False, "concentration": None,
        "concentration_unit": None, "bioactivity_type": None,
        "fragment": "1 nM", "raw": "1 nM", "quarantine": None,
    }
    row.update(over)
    return row


def dose_triple(entry):
    """(value, unit, route) out of whatever shape parse_dose returns."""
    if isinstance(entry, dict):
        return entry.get("value"), entry.get("unit"), entry.get("route")
    value, unit, route = entry
    return value, unit, route


# ------------------------------------------------------------------ as_text


class TestAsText:
    @pytest.mark.parametrize("value", [None, float("nan"), PANDAS_NAN, "", "   ", "\t\n"])
    def test_nothing_here_is_the_empty_string(self, value):
        assert preprocess.as_text(value) == ""

    def test_a_nan_never_becomes_the_word_nan(self):
        # `value or ""` on a pandas NaN writes 'nan' into the file, which then
        # loads as a compound name
        assert preprocess.as_text(PANDAS_NAN) != "nan"
        assert preprocess.as_text(float("nan")) != "nan"

    @pytest.mark.parametrize("value, expected", [
        ("nM", "nM"),
        ("  nM ", "nM"),
        # 10 probe names carry unstripped whitespace
        ("CHEMBL3092538 ", "CHEMBL3092538"),
        (" (R)-Zinc-3573", "(R)-Zinc-3573"),
        ("\t0.06 nM\n", "0.06 nM"),
    ])
    def test_strips(self, value, expected):
        assert preprocess.as_text(value) == expected

    @pytest.mark.parametrize("value, expected", [(0, "0"), (16, "16"), (0.06, "0.06")])
    def test_numbers_become_their_own_text(self, value, expected):
        assert preprocess.as_text(value) == expected

    def test_zero_is_not_nothing(self):
        assert preprocess.as_text(0) != ""


